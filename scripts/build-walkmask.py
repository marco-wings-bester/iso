#!/usr/bin/env python3
"""Build src/walkMask.js from public/assets/map.png.

The walkable area is the dirt path: pixels close to the path's tan colour.
Fences, crops, water, buildings and grass are all excluded.

Re-run after changing the map:  python3 scripts/build-walkmask.py
Requires Pillow and numpy.
"""
import base64
from collections import deque
from pathlib import Path

import numpy as np
from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parent.parent
MAP = ROOT / 'public/assets/map.png'
OUT = ROOT / 'src/walkMask.js'

PATH_RGB = (226, 176, 106)  # dirt path colour
TOLERANCE = 40              # max RGB distance from PATH_RGB
CELL = 4                    # image px per grid cell
START = (387, 1265)         # player spawn (image px); must be on the path

# Spots where the path is hidden by something you can walk under/through,
# forced walkable: (x, y, w, h) in image px.
BRIDGES = [
    (345, 1140, 80, 105),   # open gate (overhead beam + open doors)
    (130, 526, 40, 24),     # path shaded by the well roof
    (240, 320, 46, 32),     # farmhouse steps up to the door
    (468, 360, 40, 30),     # barn doorway
    (606, 786, 38, 24),     # tool shed doorway
]

img = Image.open(MAP).convert('RGB')
px = np.asarray(img).astype(int)
dist = np.sqrt(((px - np.array(PATH_RGB)) ** 2).sum(-1))
mask = Image.fromarray(((dist < TOLERANCE) * 255).astype(np.uint8))

# Close small holes (pebbles, grass tufts) in the path.
mask = mask.filter(ImageFilter.MaxFilter(5)).filter(ImageFilter.MinFilter(5))
full = np.asarray(mask) > 127
for x, y, bw, bh in BRIDGES:
    full[y:y + bh, x:x + bw] = True

h, w = full.shape
rows, cols = h // CELL, w // CELL
grid = full[:rows * CELL, :cols * CELL].reshape(rows, CELL, cols, CELL).mean((1, 3)) >= 0.5

# Keep only the region connected to the spawn point: drops tan-coloured
# specks such as hay bales and fruit that aren't part of the path.
start = (START[1] // CELL, START[0] // CELL)
assert grid[start], 'spawn point is not on the path'
keep = np.zeros_like(grid)
keep[start] = True
q = deque([start])
while q:
    r, c = q.popleft()
    for rr, cc in ((r + 1, c), (r - 1, c), (r, c + 1), (r, c - 1)):
        if 0 <= rr < rows and 0 <= cc < cols and grid[rr, cc] and not keep[rr, cc]:
            keep[rr, cc] = True
            q.append((rr, cc))
grid = keep

data = base64.b64encode(np.packbits(grid.ravel()).tobytes()).decode()
OUT.write_text(
    '// Generated by scripts/build-walkmask.py — do not edit by hand.\n'
    '// Walkable cells (the dirt path) as a row-major, MSB-first bitset, base64.\n'
    f'export const CELL = {CELL};\n'
    f'export const COLS = {cols};\n'
    f'export const ROWS = {rows};\n'
    f"export const DATA = '{data}';\n"
)
print(f'{OUT.relative_to(ROOT)}: {cols}x{rows} cells, {grid.sum()} walkable')
