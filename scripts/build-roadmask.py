#!/usr/bin/env python3
"""Build src/roadMask.js from public/assets/crossroads.jpg (Level 2).

The walkable area is the four dirt roads meeting at the crossing: pixels of
the roads' tan colour (picked by hue, as the picture is shaded and a JPEG),
with pebbles closed over and the wheat field left out. The little path off
to the bottom left isn't one of the four, so it's left out too.

Re-run after changing the picture:  python3 scripts/build-roadmask.py
Requires Pillow and numpy.
"""
import base64
from collections import deque
from pathlib import Path

import numpy as np
from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parent.parent
MAP = ROOT / 'public/assets/crossroads.jpg'
OUT = ROOT / 'src/roadMask.js'

CELL = 4                  # image px per grid cell
START = (350, 830)        # the crossing (image px); must be on a road
EXCLUDE = [
    (0, 1120, 270, 384),  # the path off to the bottom left
]

px = np.asarray(Image.open(MAP).convert('RGB')).astype(int)
R, G, B = px[..., 0], px[..., 1], px[..., 2]
road = (R > G) & (G > B) & (R > 165) & (R - B > 55) & (G - B > 25) & (R - G < 70)
wheat = (R > 215) & (G > 175) & (B < 100)
mask = Image.fromarray(((road & ~wheat) * 255).astype(np.uint8))

# Close small holes (pebbles, stones) in the roads.
mask = mask.filter(ImageFilter.MaxFilter(5)).filter(ImageFilter.MinFilter(5))
full = np.asarray(mask) > 127
for x, y, w, h in EXCLUDE:
    full[y:y + h, x:x + w] = False

h, w = full.shape
rows, cols = h // CELL, w // CELL
grid = full[:rows * CELL, :cols * CELL].reshape(rows, CELL, cols, CELL).mean((1, 3)) >= 0.5

# Keep only what's connected to the crossing.
start = (START[1] // CELL, START[0] // CELL)
assert grid[start], 'the crossing is not on a road'
keep = np.zeros_like(grid)
keep[start] = True
q = deque([start])
while q:
    r, c = q.popleft()
    for rr, cc in ((r + 1, c), (r - 1, c), (r, c + 1), (r, c - 1)):
        if 0 <= rr < rows and 0 <= cc < cols and grid[rr, cc] and not keep[rr, cc]:
            keep[rr, cc] = True
            q.append((rr, cc))
grid = keep

data = base64.b64encode(np.packbits(grid.ravel()).tobytes()).decode()
OUT.write_text(
    '// Generated by scripts/build-roadmask.py — do not edit by hand.\n'
    '// Walkable cells (the four roads at the crossroads) as a row-major, MSB-first bitset, base64.\n'
    f'export const CELL = {CELL};\n'
    f'export const COLS = {cols};\n'
    f'export const ROWS = {rows};\n'
    f"export const DATA = '{data}';\n"
)
print(f'{OUT.relative_to(ROOT)}: {cols}x{rows} cells, {grid.sum()} walkable')
# where the roads reach the picture's edges
for name, line in (('top', grid[0]), ('bottom', grid[-1]), ('left', grid[:, 0]), ('right', grid[:, -1])):
    idx = np.nonzero(line)[0]
    print(name, (idx.min() * CELL, idx.max() * CELL) if len(idx) else None)
